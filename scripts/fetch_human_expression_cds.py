"""Download real human CDS records with resumable, rate-limit-aware retrieval.

Pouyet Exp_Meiosis is an expression proxy, not a controlled synonymous-variant
assay. Sequences are annotated human CDSs fetched from Ensembl; no DNA is
synthesized or generated by a model.
"""
from __future__ import annotations

import argparse
import json
import time
from datetime import datetime, timezone
from email.utils import parsedate_to_datetime
from pathlib import Path
from typing import Any
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

from Bio.Seq import Seq

SOURCE_URL = "https://zenodo.org/api/records/835063/files/data_HumanCodonUsage.zip/content"
ENSEMBL_URL = "https://rest.ensembl.org/sequence/id/{transcript}?type=cds"
ENSEMBL_BATCH_URL = "https://rest.ensembl.org/sequence/id"
USER_AGENT = "psc-chimera-dataset-builder/2.0"
RETRYABLE_STATUS = {429, 500, 502, 503, 504}


def read_candidates(path: Path, expression_column: str) -> list[dict[str, Any]]:
    lines = [line.split() for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    if not lines:
        raise ValueError(f"Empty summary file: {path}")
    header = lines[0]
    try:
        transcript_index = header.index("Transcript")
        expression_index = header.index(expression_column)
        gene_index = header.index("Ensembl.Gene.ID")
        symbol_index = header.index("gene.symbol")
    except ValueError as exc:
        raise ValueError(f"Missing expected column in {path}: {exc}") from exc

    candidates: list[dict[str, Any]] = []
    for fields in lines[1:]:
        if len(fields) <= max(transcript_index, expression_index, gene_index, symbol_index):
            continue
        try:
            expression = float(fields[expression_index])
        except ValueError:
            continue
        transcript = fields[transcript_index]
        if expression <= 0 or not transcript.startswith("ENST"):
            continue
        candidates.append({
            "transcript": transcript,
            "gene_id": fields[gene_index],
            "expression_phenotype": (
                "mean_F_PGC_17W_and_male_pachytene_spermatocyte_round_spermatid_FPKM"
                if expression_column == "Exp_Meiosis" else expression_column
            ),
            "expression_components": (
                ["F_PGC_17W", "M_PS", "M_RS"]
                if expression_column == "Exp_Meiosis" else [expression_column]
            ),
            "normalization": "expression_raw_divided_by_max_positive_value_in_source_table",
            "gene_symbol": fields[symbol_index],
            "expression_raw": expression,
        })
    candidates.sort(key=lambda item: item["expression_raw"], reverse=True)
    return candidates


def _retry_delay(response_headers: Any, attempt: int) -> float:
    """Honor Retry-After when present; otherwise use capped exponential backoff."""
    retry_after = response_headers.get("Retry-After") if response_headers else None
    if retry_after:
        try:
            return min(120.0, max(0.0, float(retry_after)))
        except ValueError:
            try:
                retry_at = parsedate_to_datetime(retry_after)
                if retry_at.tzinfo is None:
                    retry_at = retry_at.replace(tzinfo=timezone.utc)
                return min(120.0, max(0.0, (retry_at - datetime.now(timezone.utc)).total_seconds()))
            except (TypeError, ValueError, OverflowError):
                pass
    return min(60.0, 2.0 ** attempt)


def _request_bytes(request: Request, attempts: int = 5) -> bytes | None:
    for attempt in range(attempts):
        try:
            with urlopen(request, timeout=45) as response:
                return response.read()
        except HTTPError as exc:
            if exc.code not in RETRYABLE_STATUS:
                return None
            delay = _retry_delay(exc.headers, attempt)
        except (URLError, TimeoutError, ConnectionError, OSError):
            delay = min(60.0, 2.0 ** attempt)
        if attempt + 1 < attempts:
            print(f"retry attempt={attempt + 1}/{attempts - 1} wait_seconds={delay:.1f}", flush=True)
            time.sleep(delay)
    return None


def _cache_path(transcript: str, cache_dir: Path) -> Path:
    # Ensembl transcript identifiers contain only safe filename characters.
    return cache_dir / f"{transcript}.txt"


def _fetch_one(transcript: str, cache_dir: Path) -> str | None:
    request = Request(
        ENSEMBL_URL.format(transcript=transcript),
        headers={"Accept": "text/plain", "User-Agent": USER_AGENT},
    )
    body = _request_bytes(request)
    if body is None:
        return None
    cds = body.decode("utf-8", errors="replace").strip().upper()
    if not cds or any(base not in "ACGTN" for base in cds):
        return None
    cache_dir.mkdir(parents=True, exist_ok=True)
    cache_path = _cache_path(transcript, cache_dir)
    temp_path = cache_path.with_suffix(".tmp")
    temp_path.write_text(cds + "\n", encoding="utf-8")
    temp_path.replace(cache_path)
    return cds


def fetch_cds_batch(transcripts: list[str], cache_dir: Path) -> tuple[dict[str, str], int, int]:
    """Use Ensembl's multi-ID POST endpoint, falling back to individual GETs."""
    sequences: dict[str, str] = {}
    cache_hits = 0
    failures = 0
    missing: list[str] = []
    for transcript in transcripts:
        cache_path = _cache_path(transcript, cache_dir)
        if cache_path.is_file():
            cached = cache_path.read_text(encoding="utf-8").strip().upper()
            if cached and all(base in "ACGTN" for base in cached):
                sequences[transcript] = cached
                cache_hits += 1
                continue
        missing.append(transcript)

    if missing:
        payload = json.dumps({"ids": missing, "type": "cds"}).encode("utf-8")
        request = Request(
            ENSEMBL_BATCH_URL,
            data=payload,
            method="POST",
            headers={
                "Content-Type": "application/json",
                "Accept": "application/json",
                "User-Agent": USER_AGENT,
            },
        )
        body = _request_bytes(request)
        if body is not None:
            try:
                response = json.loads(body.decode("utf-8"))
                if isinstance(response, list):
                    for item in response:
                        if not isinstance(item, dict):
                            continue
                        transcript = str(item.get("id", ""))
                        cds = str(item.get("seq", "")).strip().upper()
                        if transcript in missing and cds and all(base in "ACGTN" for base in cds):
                            sequences[transcript] = cds
                            cache_dir.mkdir(parents=True, exist_ok=True)
                            cache_path = _cache_path(transcript, cache_dir)
                            temp_path = cache_path.with_suffix(".tmp")
                            temp_path.write_text(cds + "\n", encoding="utf-8")
                            temp_path.replace(cache_path)
            except (UnicodeDecodeError, json.JSONDecodeError, TypeError, ValueError):
                pass

        # Batch APIs may omit individual unavailable IDs. Retry those individually.
        for transcript in missing:
            if transcript in sequences:
                continue
            cds = _fetch_one(transcript, cache_dir)
            if cds is None:
                failures += 1
            else:
                sequences[transcript] = cds
    return sequences, cache_hits, failures


def _valid_record(cds: str, candidate: dict[str, Any], scale: float, expression_column: str) -> dict[str, Any] | None:
    if len(cds) < 90 or len(cds) % 3:
        return None
    if cds[-3:] in {"TAA", "TAG", "TGA"}:
        cds = cds[:-3]
    if len(cds) < 90 or len(cds) % 3:
        return None
    try:
        protein = str(Seq(cds).translate(to_stop=False))
    except (AssertionError, ValueError):
        return None
    if not protein or "*" in protein or any(aa not in "ACDEFGHIKLMNPQRSTVWY" for aa in protein):
        return None
    return {
        "aa_sequence": protein,
        "codon_sequence": cds,
        "expression": min(1.0, candidate["expression_raw"] / scale),
        "expression_raw": candidate["expression_raw"],
        "expression_metric": expression_column,
        "accession": candidate["transcript"],
        "gene_id": candidate["gene_id"],
        "gene_symbol": candidate["gene_symbol"],
        "source": "Pouyet_HumanCodonUsage",
        "label_type": "proxy",
        "host": "human",
        "assay": "human_germline_expression_FPKM_proxy",
    }


def _load_checkpoint(output_path: Path) -> list[dict[str, Any]]:
    if not output_path.is_file():
        return []
    records: list[dict[str, Any]] = []
    for line_number, line in enumerate(output_path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        try:
            record = json.loads(line)
            if isinstance(record, dict) and record.get("accession") and record.get("codon_sequence"):
                records.append(record)
        except json.JSONDecodeError:
            print(f"warning: ignoring malformed checkpoint line={line_number}", flush=True)
    # Rewrite clean JSONL in case the previous process stopped mid-write.
    _write_jsonl(output_path, records)
    return records


def _write_jsonl(path: Path, records: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for record in records:
            handle.write(json.dumps(record, sort_keys=True) + "\n")


def build_records(
    summary_path: Path,
    cache_dir: Path,
    output_path: Path,
    max_records: int,
    expression_column: str,
    batch_size: int = 50,
) -> list[dict[str, Any]]:
    candidates = read_candidates(summary_path, expression_column)
    if not candidates:
        raise ValueError("No positive expression candidates found")
    scale = max(candidate["expression_raw"] for candidate in candidates)
    records = _load_checkpoint(output_path)
    if len(records) >= max_records:
        print(f"checkpoint already has {len(records)} records; requested maximum is {max_records}", flush=True)
        return records[:max_records]

    seen_accessions = {str(record.get("accession", "")) for record in records}
    seen_cds = {str(record.get("codon_sequence", "")) for record in records}
    started = time.monotonic()
    cache_hits_total = 0
    failures_total = 0
    accepted_this_run = 0

    for start in range(0, len(candidates), batch_size):
        if len(records) >= max_records:
            break
        batch_candidates = [
            candidate for candidate in candidates[start:start + batch_size]
            if candidate["transcript"] not in seen_accessions
        ]
        if not batch_candidates:
            continue

        cds_by_transcript, cache_hits, failures = fetch_cds_batch(
            [candidate["transcript"] for candidate in batch_candidates], cache_dir
        )
        cache_hits_total += cache_hits
        failures_total += failures
        new_records: list[dict[str, Any]] = []
        for candidate in batch_candidates:
            if len(records) >= max_records:
                break
            cds = cds_by_transcript.get(candidate["transcript"])
            if not cds:
                continue
            record = _valid_record(cds, candidate, scale, expression_column)
            if record is None or record["codon_sequence"] in seen_cds:
                continue
            seen_cds.add(record["codon_sequence"])
            seen_accessions.add(candidate["transcript"])
            records.append(record)
            new_records.append(record)
            accepted_this_run += 1

        # Checkpoint each batch so interruption loses at most the active batch.
        if new_records:
            with output_path.open("a", encoding="utf-8", newline="\n") as handle:
                for record in new_records:
                    handle.write(json.dumps(record, sort_keys=True) + "\n")
                handle.flush()

        elapsed = time.monotonic() - started
        print(
            f"candidates_examined={min(start + batch_size, len(candidates))}/{len(candidates)} "
            f"batch={start // batch_size + 1}/{(len(candidates) + batch_size - 1) // batch_size} "
            f"cache_hits={cache_hits_total} cached_or_fetched_cds={len(cds_by_transcript)} "
            f"accepted_this_run={accepted_this_run} total_records={len(records)} "
            f"failed_requests={failures_total} elapsed_seconds={elapsed:.1f}",
            flush=True,
        )

    print(
        f"complete candidates={len(candidates)} records={len(records)} "
        f"accepted_this_run={accepted_this_run} cache_hits={cache_hits_total} "
        f"failed_requests={failures_total} elapsed_seconds={time.monotonic() - started:.1f}",
        flush=True,
    )
    return records


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("summary", type=Path)
    parser.add_argument("--cache-dir", type=Path, default=Path(".cache/ensembl_cds_cache"))
    parser.add_argument("--output", type=Path, default=Path("data/human_expression_cds_proxy.jsonl"))
    parser.add_argument("--max-records", type=int, default=12600)
    parser.add_argument("--batch-size", type=int, default=50)
    parser.add_argument("--expression-column", default="Exp_Meiosis")
    args = parser.parse_args()
    if args.max_records <= 0:
        raise ValueError("--max-records must be positive")
    if not 1 <= args.batch_size <= 50:
        raise ValueError("--batch-size must be between 1 and 50")

    records = build_records(
        args.summary, args.cache_dir, args.output, args.max_records,
        args.expression_column, args.batch_size,
    )
    print(f"records={len(records)} saved={args.output}", flush=True)


if __name__ == "__main__":
    main()
